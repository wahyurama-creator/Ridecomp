package com.ridecomp.platform.export

import android.content.ClipData
import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import androidx.core.net.toUri
import com.ridecomp.core.engine.export.ByteSink
import com.ridecomp.core.source.DispatcherProvider
import com.ridecomp.core.usecase.ExportFileStore
import com.ridecomp.core.usecase.ExportedFile
import com.ridecomp.core.usecase.ExportedFileHandler
import com.ridecomp.core.util.runCatchingCancellable
import java.io.File
import kotlinx.coroutines.withContext

/** Folder and FileProvider names, in one place. The provider is declared by :app. */
object ExportPaths {
    /** Sub-folder of filesDir that the FileProvider exposes (res/xml/file_paths.xml). */
    const val EXPORT_DIRECTORY = "exports"

    /** Authority suffix appended to the application id. */
    const val AUTHORITY_SUFFIX = ".fileprovider"
}

/**
 * Exported FIT/GPX files in internal storage (SEC-STO-01). Names are generated by the app, never taken
 * from outside (SEC-IN-04). Streams are closed with `use` (DATA-05); all I/O on the IO dispatcher.
 */
class AndroidExportFileStore(context: Context, private val dispatchers: DispatcherProvider) : ExportFileStore {
    private val directory = File(context.filesDir, ExportPaths.EXPORT_DIRECTORY)

    override suspend fun write(fileName: String, bytes: ByteArray): String = withContext(dispatchers.io) {
        directory.mkdirs()
        File(directory, fileName).apply { writeBytes(bytes) }.absolutePath
    }

    override suspend fun stream(fileName: String, block: suspend (ByteSink) -> Unit): String =
        withContext(dispatchers.io) {
            directory.mkdirs()
            val file = File(directory, fileName)
            file.outputStream().buffered().use { output ->
                block(
                    object : ByteSink {
                        override fun write(bytes: ByteArray) {
                            output.write(bytes)
                        }
                    },
                )
            }
            file.absolutePath
        }

    override suspend fun delete(fileName: String) {
        withContext(dispatchers.io) { File(directory, fileName).delete() }
    }
}

/**
 * Shares exported files with a temporary read grant through the FileProvider, never a file:// URI
 * (SEC-PLT-04), and copies them to a user-chosen document (SAF).
 */
class AndroidExportedFileHandler(private val context: Context, private val dispatchers: DispatcherProvider) :
    ExportedFileHandler {
    private val authority: String = context.packageName + ExportPaths.AUTHORITY_SUFFIX

    override fun share(file: ExportedFile) {
        val uri = FileProvider.getUriForFile(context, authority, File(file.path))
        val send = Intent(Intent.ACTION_SEND)
            .setType(file.format.mimeType)
            .putExtra(Intent.EXTRA_STREAM, uri)
            .addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        send.clipData = ClipData.newRawUri(file.fileName, uri)
        val chooser = Intent.createChooser(send, file.fileName)
            .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_GRANT_READ_URI_PERMISSION)
        context.startActivity(chooser)
    }

    override suspend fun copyTo(file: ExportedFile, destinationUri: String): Boolean = withContext(dispatchers.io) {
        runCatchingCancellable {
            val output = requireNotNull(context.contentResolver.openOutputStream(destinationUri.toUri())) {
                "Cannot open destination"
            }
            output.use { target -> File(file.path).inputStream().use { it.copyTo(target) } }
        }.isSuccess
    }
}
